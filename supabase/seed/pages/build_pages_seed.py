#!/usr/bin/env python3
"""Turns pages.csv and descriptions.csv into an insert-only SQL migration.

Usage: python3 build_pages_seed.py > ../../migrations/<timestamp>_pages_seed.sql

Insert-only, like the park seed: a page whose handle already exists is
skipped, and so is a description that's already there, so re-running it
never overwrites changes made since (renames, team edits, Rachel's fixes).
"""
import csv, os, sys

here = os.path.dirname(os.path.abspath(__file__))
LANGS = ["en", "es", "da", "de"]


def q(v):
    if v is None or v == "":
        return "null"
    return "'" + v.replace("'", "''") + "'"


pages = list(csv.DictReader(open(os.path.join(here, "pages.csv"), encoding="utf-8")))
descs = {r["handle"]: r for r in csv.DictReader(open(os.path.join(here, "descriptions.csv"), encoding="utf-8"))}

handles = [p["handle"] for p in pages]
assert len(handles) == len(set(h.lower() for h in handles)), "duplicate handle"
missing = [h for h in handles if h not in descs]
assert not missing, f"no description for {missing}"
extra = [h for h in descs if h not in handles]
assert not extra, f"description for unknown handle {extra}"

out = []
w = out.append
w("-- Brand and shop accounts, part A, PR 1: the seeded pages.")
w("-- Generated by supabase/seed/pages/build_pages_seed.py from pages.csv and")
w("-- descriptions.csv; edit those and regenerate rather than editing this file.")
w(f"-- {len(pages)} pages, every one Unofficial or an archive, with a reserved handle")
w("-- and a factual line in English, Spanish, Danish and German.")
w("-- Insert-only: existing handles and descriptions are left alone.")
w("")
w("insert into public.pages (handle, display_name, roles, state, city, region, country, metro_area_id,")
w("  timezone, website, founded_label, ended_label, location_type, address, show_pin, closed_at)")
w("select v.handle, v.display_name, v.roles::public.page_role[], v.state::public.page_state, v.city, v.region,")
w("  v.country, m.id, v.timezone, v.website, v.founded_label, v.ended_label,")
w("  v.location_type::public.shop_location_type, v.address, v.show_pin,")
w("  case when v.state in ('out_of_business', 'closed') then now() end")
w("from (values")
rows = []
for p in pages:
    roles = "{" + ",".join(r.strip() for r in p["roles"].split(";")) + "}"
    show_pin = "false" if p["show_pin"] == "false" else "true"
    rows.append("  (" + ", ".join([
        q(p["handle"]), q(p["display_name"]), q(roles), q(p["state"]), q(p["city"]), q(p["region"]),
        q(p["country"]), q(p["metro"]), q(p["timezone"]), q(p["website"]), q(p["founded_label"]),
        q(p["ended_label"]), q(p["location_type"]), q(p["address"]), show_pin,
    ]) + ")")
w(",\n".join(rows))
w(") as v (handle, display_name, roles, state, city, region, country, metro, timezone, website,")
w("        founded_label, ended_label, location_type, address, show_pin)")
w("left join public.metro_areas m on m.name = v.metro")
w("on conflict (handle) do nothing;")
w("")
w("insert into public.page_descriptions (page_id, locale, body)")
w("select p.id, v.locale, v.body")
w("from (values")
rows = []
for h in handles:
    for lang in LANGS:
        body = descs[h][lang].strip()
        assert body, f"{h} has no {lang} line"
        assert len(body) <= 300, f"{h} {lang} too long"
        rows.append(f"  ({q(h)}, '{lang}', {q(body)})")
w(",\n".join(rows))
w(") as v (handle, locale, body)")
w("join public.pages p on p.handle = v.handle")
w("on conflict (page_id, locale) do nothing;")
sys.stdout.write("\n".join(out) + "\n")
